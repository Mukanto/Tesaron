"""From worlds to a test verdict (PREREG sections 3.3 and 4, draft 5)."""

from __future__ import annotations

import math

Z_95_ONE_SIDED = 1.6448536269514722
MIN_DEFINED = 16
WILSON_THRESHOLD = 0.80
DETERMINISTIC_TESTS = ("G1", "G2", "G3", "G4", "G5", "G6", "G7")  # G7 is G7a
QUANTITATIVE_TESTS = ("G8", "T-1")  # the primary tests (with the deterministic G7a being a criterion check)
LABEL = {"G7": "G7a"}  # the id printed in the wording

CLAIMS = {
    "G1": "Membership degrees are not turned into probabilities",
    "G2": "Encoding is reproducible in the same context (same machine, same NumPy build)",
    "G3": "A meaning unit needs its data (necessity)",
    "G4": "The decoder gives the same output for the same input (same machine, same NumPy build)",
    "G5": "Validation data do not leak into pattern computation",
    "G6": "Expansion makes no unevidenced claims",
    "G7": "None of the five degenerate baselines of SPEC §10 (echo, all_true, all_false, all_unknown, all_both) gets a "
          "positive score under the wisdom criterion",
    "G8": "Creativity (abduction) preserves meaning",
    "T-1": "Within the reasonable bounds, admitting weaker evidence does not increase new false conclusions by more "
           "than δ",
}

LIMITATION = (
    "These results come from synthetic worlds generated by code written by the same model family that designed and "
    "coded the system. The decoder was given the true rules. They say nothing about natural-language input."
)
DETERMINISTIC_NOTE = "(A check of the implementation or of the criterion, not a discovery.)"
G8_FAILS_SENTENCE = (
    "At most α the tolerance ε_d is below one atom, so a world fails when abduction changes the value of a "
    "single decided encoded atom."
)
T1_HOLDS_SENTENCE = (
    "A HOLDS can result from calibrated bounds that exclude the 0.60 source on most worlds; see the structure counts."
)
EXPECTED_PARAGRAPH = (
    "Expected verdicts given the pilot (R1-10). If the test worlds behave like the development worlds, T-1 and G8 are "
    "expected to FAIL. T-1 may also end in \"insufficient worlds\": on development worlds its number of defined "
    "worlds varied strongly between calibration draws. Under the 28/30 rule, P(HOLDS) is about 0.003 at a per-world rate of 0.71 (T-1), and about 0 at "
    "0.30 (G8). The test τ will differ from the development τ, which is a caveat. A different outcome would mean "
    "that the test worlds, or for T-1 the calibrated bounds, differ from the development ones (see the structure "
    "counts)."
)


def wilson_lower(successes: int, n: int, z: float = Z_95_ONE_SIDED) -> float:
    """One-sided Wilson score lower bound of a proportion."""
    if n <= 0:
        return 0.0
    p = successes / n
    z2 = z * z
    centre = p + z2 / (2 * n)
    spread = z * math.sqrt(p * (1 - p) / n + z2 / (4 * n * n))
    return (centre - spread) / (1 + z2 / n)


STRUCTURE_KEYS = ("some_alpha_le_060_feasible", "alpha_ge_085_feasible", "t1_window_pairs", "t1_crossing_pairs",
                  "t1_cross_080_085")


def structure_counts(outcomes: list[tuple[int, str]], structure: list[dict]) -> dict:
    """Counts of the I-5 structure over the defined T-1 worlds. structure[i] is the t1_structure dict of the world of
    outcomes[i]; only worlds with a defined T-1 outcome are counted."""
    if len(structure) != len(outcomes):
        raise ValueError("structure and outcomes must describe the same worlds")
    rows = [s for (_, o), s in zip(outcomes, structure) if o != "UNDEFINED"]
    pairs = {}
    for key in ("t1_window_pairs", "t1_crossing_pairs", "t1_cross_080_085"):
        vals = [s[key] for s in rows]
        pairs[key] = {"hold": sum(v is True for v in vals), "fail": sum(v is False for v in vals),
                      "none": sum(v is None for v in vals)}
    return {
        "n": len(rows),
        "alpha_le_060": sum(bool(s["some_alpha_le_060_feasible"]) for s in rows),
        "alpha_ge_085": sum(bool(s["alpha_ge_085_feasible"]) for s in rows),
        **pairs,
    }


def structure_text(c: dict) -> str:
    w, x, y = c["t1_window_pairs"], c["t1_crossing_pairs"], c["t1_cross_080_085"]
    return (
        f"Structure (I-5): of {c['n']} defined worlds, {c['alpha_le_060']} had some feasible α ≤ 0.60 and "
        f"{c['alpha_ge_085']} some feasible α ≥ 0.85. Pairs inside α 0.65–0.80: {w['hold']} hold, {w['fail']} fail, "
        f"{w['none']} none. Pairs crossing 0.60/0.65: {x['hold']}/{x['fail']}/{x['none']}. "
        f"Pairs crossing 0.80/0.85: {y['hold']}/{y['fail']}/{y['none']}."
    )


def t1_sentence(c: dict) -> str:
    return (
        f"In these worlds T-1 compares regimes of the three source reliabilities: on {c['alpha_le_060']} of {c['n']} "
        f"defined worlds the feasible set reached α ≤ 0.60, where the 0.60 source is admitted, and on "
        f"{c['alpha_ge_085']} it reached α ≥ 0.85, where the 0.80 source is excluded. T-1's outcome depends strongly "
        f"on the calibrated bounds, which vary between calibration draws. It is not a graded test of the thesis."
    )


def hypothesis_summary(outcomes: list[tuple[int, str]], n_hypotheses: list[int]) -> dict:
    """Minimum, median and maximum number of abduction hypotheses at (alpha0, k = 10) over the defined G8 worlds.
    The median is exact: with an even number of worlds it is the mean of the two middle values, which is a whole or a
    half number and is printed as a decimal."""
    if len(n_hypotheses) != len(outcomes):
        raise ValueError("n_hypotheses and outcomes must describe the same worlds")
    vals = sorted(int(n) for (_, o), n in zip(outcomes, n_hypotheses) if o != "UNDEFINED")
    if not vals:
        return {"n": 0, "min": None, "median": None, "max": None, "text": "Hypotheses at (α₀, k = 10) over the "
                "defined worlds: none (no defined worlds)."}
    mid = len(vals) // 2
    twice = 2 * vals[mid] if len(vals) % 2 else vals[mid - 1] + vals[mid]  # twice the median, an integer
    median = f"{twice // 2}" if twice % 2 == 0 else f"{twice // 2}.5"
    note = " (the mean of the two middle values)" if len(vals) % 2 == 0 else ""
    return {
        "n": len(vals), "min": vals[0], "median": median, "max": vals[-1],
        "text": f"Hypotheses at (α₀, k = 10) over the defined worlds: minimum {vals[0]}, median {median}{note}, "
                f"maximum {vals[-1]}.",
    }


def aggregate_test(test_id: str, outcomes: list[tuple[int, str]], detector_both: int | None = None,
                   failed_parts: dict | None = None, structure: list[dict] | None = None,
                   n_hypotheses: list[int] | None = None) -> dict:
    """Verdict of one test from [(world_seed, "HOLDS" | "FAILS" | "UNDEFINED"), ...] in world order.

    Deterministic tests (G1-G7a): FAILS if any defined world FAILS (A-8), even with fewer than 16 defined worlds;
    otherwise HOLDS with at least 16 defined worlds, else "insufficient worlds". Quantitative tests (G8, T-1):
    "insufficient worlds" with fewer than 16 defined worlds; otherwise HOLDS iff the one-sided 95% Wilson lower bound of
    the HOLDS share among defined worlds is at least 0.80, else FAILS. UNDEFINED worlds are excluded and counted.
    detector_both: the number of worlds on which the fixed system and its twin both HOLD (section 6.2); if it is above
    0 a HOLDS verdict is qualified.
    failed_parts (G1 only): {world_seed: ["(ii)", ...]}; the FAILS sentence names the parts that failed in the first
    failing world.
    structure (T-1 only, required): the t1_structure dict of every world, in the order of outcomes (section 5, I-5);
    the structure counts are printed next to the verdict.
    n_hypotheses (G8 only, required): the number of hypotheses at (alpha0, k = 10) of every world, in the order of
    outcomes; the minimum, median and maximum over the defined worlds are printed next to the verdict.
    """
    if test_id not in CLAIMS:
        raise ValueError(f"unknown test {test_id!r}")
    for _, o in outcomes:
        if o not in ("HOLDS", "FAILS", "UNDEFINED"):
            raise ValueError(f"bad outcome {o!r}")
    if test_id == "T-1" and structure is None:
        raise ValueError("T-1 needs the per-world structure (I-5)")
    if test_id == "G8" and n_hypotheses is None:
        raise ValueError("G8 needs the per-world number of hypotheses")
    ident = LABEL.get(test_id, test_id)
    n_holds = sum(o == "HOLDS" for _, o in outcomes)
    n_fails = sum(o == "FAILS" for _, o in outcomes)
    n_undefined = sum(o == "UNDEFINED" for _, o in outcomes)
    n_defined = n_holds + n_fails
    first_fail = next((s for s, o in outcomes if o == "FAILS"), None)
    lower = wilson_lower(n_holds, n_defined) if test_id in QUANTITATIVE_TESTS and n_defined else None

    if test_id in DETERMINISTIC_TESTS:
        if n_fails > 0:
            verdict = "FAILS"
        elif n_defined >= MIN_DEFINED:
            verdict = "HOLDS"
        else:
            verdict = "INSUFFICIENT"
    elif n_defined < MIN_DEFINED:
        verdict = "INSUFFICIENT"
    else:
        verdict = "HOLDS" if lower >= WILSON_THRESHOLD else "FAILS"

    claim = CLAIMS[test_id]
    if verdict == "INSUFFICIENT":
        text = f"{ident}: insufficient worlds ({n_defined} defined, {MIN_DEFINED} required); no verdict."
    elif test_id in DETERMINISTIC_TESTS:
        if verdict == "HOLDS":
            text = (f"{ident} holds: {claim}, in all {n_defined} defined test worlds ({n_undefined} undefined). "
                    f"{DETERMINISTIC_NOTE}")
        else:
            text = (f"{ident} does not hold: {n_fails} of {n_defined} defined test worlds fail; the first failing "
                    f"world is {first_fail}.")
            if test_id == "G1" and failed_parts and failed_parts.get(first_fail):
                text += f" Failed parts in the first failing world: {', '.join(failed_parts[first_fail])}."
    else:
        b = f"{lower:.3f}"
        if verdict == "HOLDS":
            text = (f"{ident} holds: {claim}. {n_holds} of {n_defined} defined worlds hold (Wilson lower bound {b}, "
                    f"threshold 0.80); {n_undefined} undefined.")
        else:
            text = (f"{ident} does not hold: {n_holds} of {n_defined} defined worlds hold (Wilson lower bound {b}, "
                    f"threshold 0.80); {n_undefined} undefined; the first failing world is {first_fail}.")
        if test_id == "G8" and verdict == "FAILS":
            text += " " + G8_FAILS_SENTENCE
    hyp = None
    if test_id == "G8":
        hyp = hypothesis_summary(outcomes, n_hypotheses)
        text += " " + hyp["text"]
    counts, struct_text = None, None
    if test_id == "T-1":
        counts = structure_counts(outcomes, structure)
        struct_text = structure_text(counts)
        text += " " + t1_sentence(counts)  # for every verdict, "insufficient worlds" included (R3-9)
        text += " " + struct_text
        if verdict == "HOLDS":
            text += " " + T1_HOLDS_SENTENCE
    qualifier = None
    if verdict == "HOLDS" and detector_both:
        qualifier = f"the detector did not separate on {detector_both} worlds"
        text += f" ({qualifier})"
    return {
        "test": test_id,
        "id": ident,
        "verdict": verdict,
        "n_holds": n_holds,
        "n_fails": n_fails,
        "n_undefined": n_undefined,
        "n_defined": n_defined,
        "wilson_lower": lower,
        "first_failing_world": first_fail,
        "text": text,
        "expected_paragraph": EXPECTED_PARAGRAPH if test_id in QUANTITATIVE_TESTS else None,
        "detector_qualifier": qualifier,
        "hypotheses": hyp,
        "structure": counts,
        "structure_text": struct_text,
        "limitation": LIMITATION,
    }


def undefined_as_fails(outcomes: list[tuple[int, str]]) -> dict:
    """Descriptive (R1-13): the Wilson share with UNDEFINED worlds counted as FAILS."""
    n = len(outcomes)
    holds = sum(o == "HOLDS" for _, o in outcomes)
    return {"n_holds": holds, "n": n, "wilson_lower": wilson_lower(holds, n) if n else None}


def verdict_table(per_test: dict[str, list[tuple[int, str]]], detector_both: dict | None = None,
                  failed_parts: dict | None = None, structure: list[dict] | None = None,
                  n_hypotheses: list[int] | None = None) -> dict:
    """The section 4 table: one row per test, no combined verdict, the limitation sentence next to every verdict."""
    detector_both = detector_both or {}
    rows = [
        aggregate_test(t, per_test[t], detector_both.get(t), failed_parts if t == "G1" else None,
                       structure if t == "T-1" else None, n_hypotheses if t == "G8" else None)
        for t in (*DETERMINISTIC_TESTS, *QUANTITATIVE_TESTS) if t in per_test
    ]
    return {"rows": rows, "limitation": LIMITATION}
